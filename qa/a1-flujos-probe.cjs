const { chromium } = require('./playwright-system-chrome.cjs');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', (e) => console.error('PAGEERROR', e.message));
  page.on('console', (m) => { if (m.type() === 'error') console.error('CONSOLE', m.text()); });
  await page.goto('http://127.0.0.1:8877/PRUEBA_CON_PERSONAS/RONDA_FINAL_E0_E9/inicio.html', { waitUntil: 'domcontentloaded' });
  await page.locator('#participant').selectOption('P2');
  await page.locator('[data-route="A"]').click();
  await page.waitForTimeout(600);
  console.log('URL', page.url());
  console.log('BODY', (await page.locator('body').innerText()).slice(0, 1800));
  console.log('CURRENT', await page.locator('body').getAttribute('data-current'));
  console.log('M4T', await page.locator('#m4t').count(), 'overlay', await page.locator('#m4t [role="dialog"], #m4t .m4t-sheet').count());
  await page.screenshot({ path: 'qa/a1-probe-a.png', fullPage: true });
  console.log('selectors', await page.locator('#m4tNombre,#m4tOk,#m4tGo,#m4tMore,#query,#search button[type=submit]').count());
  await page.getByRole('button', { name: 'Ir a Google' }).click();
  await page.locator('#query').fill('café para hotel');
  await page.locator('#search button[type="submit"]').click();
  await page.locator('#serp-list').waitFor({ state: 'visible' });
  await page.screenshot({ path: 'qa/a1-probe-serp.png', fullPage: true });
  console.log('SERP', (await page.locator('#serp-list').innerText()).slice(0, 900));
  await page.locator('#organic-title').click();
  await page.waitForLoadState('domcontentloaded');
  console.log('SOLUTION', page.url());
  console.log('SOLUTION TEXT', (await page.locator('body').innerText()).slice(0, 1300));
  console.log('SOLUTION LINKS', await page.locator('a[href]').evaluateAll((xs) => xs.map((x) => ({ text: x.innerText.trim(), href: x.href })).filter((x) => /index.html|#C0|C03|C04/i.test(x.href + x.text)).slice(0, 20)));
  await page.screenshot({ path: 'qa/a1-probe-solution.png', fullPage: true });
  await page.getByRole('link', { name: /IR AL PORTAL/i }).click();
  await page.waitForFunction(() => (location.hash || '').split('?')[0] === '#C03');
  await page.locator('#m4FEmail').waitFor({ state: 'visible' });
  console.log('PORTAL C03', (await page.locator('body').innerText()).slice(-2000));
  console.log('M4T rect', await page.locator('#m4tMore').boundingBox());
  console.log('other rect', await page.getByRole('button', { name: 'Otro correo' }).boundingBox());
  await page.screenshot({ path: 'qa/a1-probe-c03.png' });
  const crmContext = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
  const crm = await crmContext.newPage();
  crm.on('pageerror', (e) => console.error('CRM PAGEERROR', e.message));
  await crm.goto('http://127.0.0.1:8877/PRUEBA_CON_PERSONAS/RONDA_FINAL_E0_E9/inicio.html', { waitUntil: 'domcontentloaded' });
  await crm.locator('[data-route="C"][data-role="ventas"]').click();
  await crm.waitForFunction(() => (location.hash || '').split('?')[0] === '#R00');
  console.log('R00', await crm.locator('body').getAttribute('data-current'), (await crm.locator('#app').innerText()).slice(0, 900));
  await crm.locator('#m4User').fill('paula.diaz');
  await crm.locator('#m4Pass').fill('prueba');
  await crm.locator('.m5-login button[type="submit"]').click();
  await crm.waitForFunction(() => (location.hash || '').split('?')[0] !== '#R00');
  console.log('AFTER LOGIN', crm.url(), (await crm.locator('#app').innerText()).slice(0, 1200));
  await crm.screenshot({ path: 'qa/a1-probe-crm.png', fullPage: true });
  await crmContext.close();
  await browser.close();
})().catch((error) => { console.error(error); process.exit(1); });
